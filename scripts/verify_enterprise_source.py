#!/usr/bin/env python3
"""Offline source/syntax/safety checks; not a replacement for a .NET build or live tests."""
from pathlib import Path
from datetime import datetime,timezone
from pygments import lex
from pygments.lexers import CSharpLexer
from pygments.token import Error,Punctuation
import json,re,sys

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'src'/'Jcf.NetworkManager'
results=[]
def check(name,ok,detail=''):
    results.append({'check':name,'status':'PASS' if ok else 'FAIL','detail':detail})
    print(('PASS ' if ok else 'FAIL ')+name+((' - '+detail) if detail else ''))

def content(path):return (SRC/path).read_text(encoding='utf-8')

policy=content('Workflow/NetworkChangePolicy.cs')
gateway=content('Workflow/ArubaLabApprovedChangeGateway.cs')
program=content('Program.cs')
identity=content('Services/LocalAuthEndpoints.cs')
models=content('Domain/WorkflowModels.cs')
appsettings=content('appsettings.json')
check('SQL and local Identity', 'AddIdentity<OperatorUser,IdentityRole<Guid>>' in program and 'UseSqlServer(connection' in program)
check('User bootstrap no hard-coded password', 'BootstrapAdmin:PasswordFile' in content('Services/LocalIdentityBootstrap.cs') and 'Aruba123' not in str(list(SRC.rglob('*.cs'))))
check('20 and 40 MHz policy','ApprovedWidthsMhz = [20, 40]' in policy and 'SetChannelPolicy' in policy)
check('Exclude DFS channels','52,56,60,64,100,104,108,112,116,120,124,128,132,136,140,144' in policy)
check('Channel 165 cannot be paired 40 MHz', 'width==40 && n==165' in policy)
check('Approval and payload protection', 'ApprovedPayloadSha256' in content('Workflow/ChangeWorkflowService.cs') and 'RequiresSecondApprover' in policy)
check('Restricted device-write execution (explicit allowlist, keyed on the target device)', 'policy.Permits(device.ManagementIp)' in content('Workflow/ChangeWorkflowService.cs') and 'if(!device.IsSimulated)' in content('Workflow/ChangeWorkflowService.cs') and 'LiveLabWrites:Enabled' in content('Workflow/DeviceWritePolicy.cs') and 'AllowedCidrs' in content('Workflow/DeviceWritePolicy.cs'))
check('Unsupported device writes denied', 'Instant action not allowlisted' in gateway and 'Switch action not allowlisted' in gateway)
check('Only approved lab device actions supported', 'ConfigAction.CreateSsid or ConfigAction.ChangeBandSteering or ConfigAction.ChangeMinTxPower' in gateway)
check('Login anti-forgery and lockout','ValidateRequestAsync' in identity and 'lockoutOnFailure:true' in identity)
check('JSON mutating APIs require anti-CSRF', 'IsRequestValidAsync' in program and '/security/csrf' in program and 'X-CSRF-TOKEN' in program)
check('AOS-CX documented session and redaction', 'rest/latest/login?username=' in content('Connectors/CxConnector.cs') and 'x-use-csrf-token' in content('Connectors/CxConnector.cs') and 'DeviceErrors.Describe' in content('Connectors/CxConnector.cs'))
check('Cluster-bound concurrency limit', 'MaxConcurrentClusterPolls' in content('Services/Workers.cs') and 'SemaphoreSlim' in content('Services/Workers.cs'))
check('Certificate validation enforced (pinned leaf or OS chain; never blanket-accept)','ServerCertificateCustomValidationCallback' in content('Connectors/DeviceHttpFactory.cs') and 'CryptographicOperations.FixedTimeEquals' in content('Connectors/DeviceHttpFactory.cs') and 'DangerousAcceptAnyServerCertificateValidator' not in content('Connectors/DeviceHttpFactory.cs'))
check('Audit data immutable in EF','EnforceAppendOnlyAudit' in content('Data/NetworkDbContext.cs'))
check('No automatic production database migration','GetPendingMigrationsAsync' in content('Services/DemoSeed.cs') and 'db.Database.MigrateAsync()' not in content('Services/DemoSeed.cs'))
check('Diagnostic target CIDR restriction','AddressPolicy.IsAllowed' in content('Services/NetworkDiagnosticsService.cs'))
check('Client identifiers pseudonymized','HMACSHA256.HashData' in content('Services/DeviceService.cs'))
check('Read-only optimization source','IApprovedChangeGateway' not in content('Services/AnalysisService.cs'))
check('No test credentials in C#',not any('Aruba123' in f.read_text(errors='ignore') for f in SRC.rglob('*.cs')))
check('JSON configuration parses',bool(json.loads(appsettings)))
check('Local auth UI and SQL runbook exist',(SRC/'Components/Pages/Users.razor').exists() and (ROOT/'docs/DEPLOYMENT_AND_OPERATIONS.md').exists())
check('SRS implementation matrix exists',(ROOT/'docs/SRS_IMPLEMENTATION_MATRIX.md').exists())

def handwritten_sources():
    # Lint hand-written code only: build output (bin/obj) and tool-generated files such as EF Core migrations
    # ("// <auto-generated />", "#nullable disable") are validated by the compiler, not this lexer.
    for f in SRC.rglob('*.cs'):
        if {'bin','obj'} & set(f.relative_to(SRC).parts): continue
        if f.read_text(encoding='utf8',errors='ignore').lstrip('\ufeff').startswith('// <auto-generated'): continue
        yield f

issues=[]
linted=list(handwritten_sources())
for f in linted:
    brackets=[]
    # Pygments' C# lexer does not understand directives such as '#nullable disable'; blank them (keeps line numbers).
    text=re.sub(r'(?m)^[ \t]*#(?:nullable|pragma|region|endregion)\b.*$','',f.read_text(encoding='utf8'))
    for token,value in lex(text,CSharpLexer()):
        if token in Error:issues.append((str(f.relative_to(ROOT)),'lex-error',repr(value)))
        if token in Punctuation:
            for c in value:
                if c in '{[(':brackets.append(c)
                elif c in '}])':
                    expected={'}':'{',']':'[',')':'('}[c]
                    if not brackets or brackets[-1]!=expected:
                        issues.append((str(f.relative_to(ROOT)),'unmatched',c));continue
                    brackets.pop()
    if brackets: issues.append((str(f.relative_to(ROOT)),'unclosed',str(brackets[-10:])))
check('C# lexer and balanced delimiters',not issues,f'{len(linted)} hand-written files, {len(issues)} findings')
for issue in issues[:10]:print('    '+str(issue))

report={'tool':'JCF enterprise source static verification','at_utc':datetime.now(timezone.utc).isoformat(),
        'status':'STATIC_PASS' if all(r['status']=='PASS' for r in results) else 'STATIC_FAIL',
        'compiled_dotnet_tests':'NOT_RUN_DOTNET_SDK_UNAVAILABLE',
        'live_hardware_tests':'NOT_RUN_NO_ACCESS',
        'checks':results}
(ROOT/'docs/ENTERPRISE_STATIC_VALIDATION.json').write_text(json.dumps(report,indent=2))
print('RESULT:',report['status'],len(results),'checks; this does not certify production readiness.')
sys.exit(0 if report['status']=='STATIC_PASS' else 1)
